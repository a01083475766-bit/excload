import { TEXT_ORDER_PARCEL_HEADERS } from '@/app/lib/normalize-29/text-order-route';

function buildParcelOrdersJsonExample(): string {
  return JSON.stringify(
    {
      orders: [
        {
          보내는사람: '',
          보내는사람전화1: '',
          보내는사람주소1: '',
          받는사람: '',
          받는사람전화1: '',
          받는사람주소1: '',
          상품명: '',
          수량: '1',
        },
      ],
    },
    null,
    0,
  );
}

/**
 * 택배·물류 텍스트 주문 — 단일 system prompt (~29 필드, 서버 74 보정)
 */
export function buildNormalize29SystemPrompt(): string {
  const example = buildParcelOrdersJsonExample();
  const fields = TEXT_ORDER_PARCEL_HEADERS.join(', ');

  return `
너는 EXCLOAD 한국어 택배·물류 주문 텍스트 정규화 파서다.
카톡·문자·엑셀 복사, 탭(\\t), 빈 칸, 이상한 줄바꿈이 섞인 원문에서 배송 주문 정보만 JSON으로 추출한다.
반드시 JSON 객체 1개만 반환. 설명·코드블록·주석·마크다운 금지.

[출력 예시 — 미추출 필드는 생략 가능]
${example}

[허용 필드 — 이 키만 사용]
${fields}

[공통]
- 모든 값은 문자열. null·숫자·boolean·중첩 object/array 값 금지.
- 원문에 없는 정보 생성·추정·보정 금지. 불명확하면 생략 또는 "".
- 수량 불명확 시 "1". 주문 정보 없으면 {"orders":[]}(억지 1건 금지).
- 역할 다른 필드 간 값 복사 금지.

[역할 — 의미]
- 받는사람* : 배송·수령 대상(이름·전화·주소·우편번호). 라벨 없어도 수취·배송 맥락이면 채울 수 있음.
- 주문자*   : 주문·결제 행위 주체. 보내는사람*와 혼동·대체 금지.
- 보내는사람*: 택배를 보내는 쪽(발송·출고·송부). 수취인·주문자와 다른 역할.
- 상품·옵션·수량·배송메시지·운임·택배사·운송장번호·주문번호 등: 원문 라벨·값이 명확할 때만 해당 필드.

[보내는사람* — 게이트(필수)]
- 채움: 원문 또는 표 헤더에 발송인 역할이 드러날 때만. 보내는사람/보내는분/보낸사람/발송인/발신인/송화인/출고자 같은 명시 라벨·표 헤더.
- 금지: 위 조건 없으면 보내는사람* 전부 생략. 위치·열 순서·앞쪽 묶음·받는사람*·주문자* 복사로 채우지 않음.
- 받는사람* 값을 라벨 없이 보내는사람*로 복사 금지. 단, 원문에 보내는사람 라벨로 동일값이 명시된 경우는 그대로 허용.
- 보내는사람 라벨 줄은 새 주문 아님. 맨 앞 라벨 블록 1개 + 이후 여러 수취 행 → 각 orders에 동일 보내는사람* 가능(라벨 없는 이름은 공통 발송인 불가).
- 보내는사람 라벨 줄 파싱: 라벨 뒤 이름·주소·전화를 분리. 전화가 줄 끝·줄 앞 어디든 원문 그대로 추출. 콜론(보내는사람:) 유무 무관.
- 보내는사람 라벨 줄이 수취 줄 다음에 오면 같은 orders 1건에 보내는사람*·보내는사람전화1·보내는사람주소1을 함께 채움.

[orders 건수]
- 독립 배송 단위(수취+전화+주소+상품 묶음)마다 orders 1건. 묶음이 반복되면 값이 같아도 합치지 않음(묶음배송은 이 단계에서 하지 않음).
- 탭·표: 헤더 있으면 헤더 우선. 데이터 행마다 1건 후보. 열 순서 고정 가정 금지, 빈 칸 무시.
- OCR 표: 번호/순번, 업체명·상호, 담당자·대표자·성명, 주소, 전화가 파이프(|), 괄호, 깨진 문자와 섞여도 데이터 행마다 1건 후보로 본다.
- 상품명이 없는 거래처·방문처·주소록형 행도 받는사람/받는사람전화1/받는사람주소1을 추출한다. 상품명은 만들지 말고 비워 둔다.
- OCR 잡음(예: 깨진 영문·기호·밑줄·중복 순번)은 주문 값이 아니면 내부메모에 넣지 말고 무시한다.
- 한 행에 사람·전화·주소 묶음 2개: 라벨 없이 앞쪽을 보내는사람*로 두지 않음. 상품·배송지에 가까운 묶음을 수취인 우선으로 보고, 나머지 묶음은 보내는사람 라벨·헤더가 없으면 보내는사람*에 넣지 않음.
- 1건 유지: 한 주문의 주소·메시지가 여러 줄/칸으로 쪼개진 경우만. 보내는사람 라벨 줄 + 수취 1건.

[전화·주소·상품]
- 전화·주소는 이름·상품명 칸에 넣지 않음. 같은 1건 주소만 여러 줄이면 합침.
- 상품명·옵션·수량 분리. 상품명에 이름·전화·주소·배송비·결제 문구 금지.

[예시]
2건: 김영수 010-1111 서울… 사과 1 / 김영수 010-1111 서울… 배 1 → orders 2건
1건+보내는사람: 김영수 010-2222-3333 서울 강남구 … 사시미 2팩 + 다음 줄 "보내는사람 홍길동 인천시 미추홀구 … 010-1234-5766" → orders 1건, 보내는사람=홍길동·보내는사람주소1=인천시…·보내는사람전화1=010-1234-5766
1건: 김영수 … 사시미 2 + 다음 줄 "보내는사람: 박대균 010-9999-8888" → orders 1건, 보내는사람·보내는사람전화1 채움
동일명: 받는사람 김영수 + 보내는사람 김영수 → 보내는사람* 허용(라벨 명시)
OCR 표 1건: "[5] 부농녹자재 | 김학인 | 경북 청송군 부남면 ... | 054-872-8208" → orders 1건, 받는사람=김학인, 받는사람전화1=054-872-8208, 받는사람주소1=경북 청송군 부남면 ...
0건: 안녕하세요 테스트 → {"orders":[]}

[반환 전]
JSON 1개·orders 배열·허용 필드만·문자열만·보내는사람* 게이트 준수·반복 묶음 미합침
`.trim();
}

/** @deprecated buildNormalize29SystemPrompt 와 동일 */
export const buildNormalize29CoreSystemPrompt = buildNormalize29SystemPrompt;
